/**
 * Generates NSIS protocol handler registration script
 * 
 * Reads database protocols from electron-builder-config.js and generates
 * a NSIS installer section that registers all URL schemes in Windows registry.
 * 
 * Called automatically during build process.
 * Generated output: apps/studio/build/win/protocol-handler.nsi
 */

const fs = require('fs')
const path = require('path')

const electronBuilderConfig = require('../../electron-builder-config.js')
const schemes = electronBuilderConfig.protocols.flatMap(p => p.schemes)

const header = `; Auto-generated NSIS protocol handler registration
; ⚠️ WARNING: DO NOT EDIT - This file is auto-generated on every build
;
; Generated by: apps/studio/build/win/generate-nsis-protocols.js
; Source protocols from: apps/studio/electron-builder-config.js (protocols array)
;
; To add/remove database URL schemes:
; 1. Edit the 'protocols' array in apps/studio/electron-builder-config.js
; 2. Rebuild the Windows installer
; 3. This file will be automatically regenerated with the new schemes
;
; Example protocol entry in electron-builder-config.js:
; {
;   name: "PostgreSQL URL scheme",
;   schemes: ["postgresql", "postgres", "psql"],
;   role: "Editor"
; }
;
; Registered protocols (\${schemes.length} total): \${schemes.join(', ')}

`;

let installSection = `Section "Register Protocol Handlers"
`;
schemes.forEach(scheme => {
  const displayName = scheme.charAt(0).toUpperCase() + scheme.slice(1);
  installSection += `  WriteRegStr HKCR "\${scheme}" "" "URL:\${displayName} Connection"
  WriteRegStr HKCR "\${scheme}" "URL Protocol" ""
  WriteRegStr HKCR "\${scheme}\\shell\\open\\command" "" '"$INSTDIR\\Beekeeper Studio.exe" "%1"'
  
`;
});
installSection += `SectionEnd
`;
let uninstallSection = `Section "Uninstall"
`;
schemes.forEach(scheme => {
  uninstallSection += `  DeleteRegKey HKCR "\${scheme}"
`;
});
uninstallSection += `SectionEnd
`;
const nsisCode = header + installSection + uninstallSection;
const outputPath = path.join(__dirname, 'protocol-handler.nsi');
fs.writeFileSync(outputPath, nsisCode);
console.log(`✅ Generated \${outputPath}`);
console.log(`   Registered \${schemes.length} protocol handlers`);